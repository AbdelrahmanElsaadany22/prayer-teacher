  Takbeer: 'تكبيرة الإحرام',
  Qiyam: 'القيام',
  "Ruku'": 'الركوع',
  "I'tidal": 'الاعتدال',
  'Sujood 1': 'السجود',
  'Sujood 2': 'السجود',
  Sujood: 'السجود',
  Juloos: 'الجلسة',
  Tashahhud: 'التشهد',
  'Tasleem (right)': 'التسليم يمينًا',
  'Tasleem (left)': 'التسليم يسارًا',
